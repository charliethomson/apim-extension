//! `repo.checks` — the gate on `.kiln/` itself.
//!
//! The standards' `ci-cd.md` requires it: `.woodpecker/` is generated, so
//! something has to fail when the committed projection and the source disagree.
//! Not templated by libci, so it is written out here.
//!
//! # Emit into a scratch dir, don't regenerate in place
//!
//! kiln's own repo gates this with `emit --out "$scratch"` and `diff -ru`,
//! because `emit` overwrites the files it produces and **deletes nothing**: a
//! pipeline removed from `main.rs` leaves an orphan `.yml` that `git diff`
//! cannot see, and an orphan Woodpecker workflow is not inert — it keeps
//! running. A diff against a freshly emitted tree catches content drift,
//! missing files and orphans at once.
//!
//! The comparison is per file, in both directions, with the orphan half judging
//! only files that carry `emit`'s header, so a hand-written workflow can sit
//! beside the generated ones without this gate objecting to it. (After ttr3's
//! `repo.checks`.)
//!
//! # Re-exec, don't shell out to cargo
//!
//! The first version ran `cargo run --manifest-path .kiln/Cargo.toml -- emit`
//! and failed in CI: the generated step builds `.kiln/` **offline** against
//! what the `kiln-fetch` step resolved, with a vendor config and no key, so a
//! fresh `cargo run` inside the body has neither. The job is already running
//! the built binary, so it re-execs that instead — no cargo, no network, no
//! git.

use super::IMAGE as TOOLCHAIN_IMAGE;
use kiln::prelude::*;

/// Where `emit` writes, and the lockfile `describe` writes.
const OUT: &str = ".woodpecker";
const LOCK: &str = ".kiln/lock.json";

/// `emit`'s first line. A file without it is hand-written and not ours to
/// judge.
const HEADER: &str = "Generated by `kiln emit woodpecker`";

/// What to run to fix either half.
const FIX: &str = "cargo run --manifest-path .kiln/Cargo.toml -- emit woodpecker\n\
                   cargo run --manifest-path .kiln/Cargo.toml -- describe > .kiln/lock.json";

/// `repo.checks`.
pub fn checks() -> Pipeline {
    Pipeline::new("repo.checks")
        .describe("`.woodpecker/` and `.kiln/lock.json` are what `.kiln/src` emits")
        .on(Push::to("main").paths([".kiln/**", ".woodpecker/**"]))
        .on(Manual)
        .serialize(Always::cancel())
        .job("kiln", |j| {
            j.on(Linux).image(TOOLCHAIN_IMAGE).run(|ctx| {
                workflows(ctx)?;
                lockfile(ctx)
            })
        })
}

/// This binary, to re-exec. `current_exe` rather than a cargo invocation: see
/// the module docs.
fn me(ctx: &Ctx) -> Result<PathBuf> {
    let exe = std::env::current_exe().map_err(|e| ctx.err(format!("cannot find my own path: {e}")))?;
    Utf8PathBuf::from_path_buf(exe).map_err(|p| ctx.err(format!("my own path is not UTF-8: {}", p.display())))
}

/// Every generated workflow matches a fresh emit, and no generated workflow is
/// left over from a pipeline that is no longer registered.
fn workflows(ctx: &Ctx) -> Result<()> {
    ctx.step("woodpecker drift", |ctx| {
        // Emptied first, for the very reason this gate exists: `emit` overwrites
        // but never deletes. A scratch directory left by an earlier run on the
        // same machine keeps the files of pipelines that have since been
        // unregistered, and they then read as missing from `.woodpecker/` — a
        // failure about nothing. Fresh on CI, reused by anyone running this
        // locally twice, which is how it was found.
        let scratch = ctx.tmp().join("emit");
        ctx.run("rm", ["-rf"]).arg(&scratch).call()?;
        ctx.run(me(ctx)?, ["emit", "woodpecker", "--out"]).arg(&scratch).in_dir(ctx.workspace()).call()?;

        let committed = ctx.workspace().join(OUT);
        let mut drifted = Vec::new();
        let mut missing = Vec::new();

        let fresh = listing(ctx, &scratch)?;
        for name in &fresh {
            let a = scratch.join(name);
            let b = committed.join(name);
            if !ctx.exists(&b) {
                missing.push(name.clone());
            } else if ctx.read(&a)? != ctx.read(&b)? {
                drifted.push(name.clone());
            }
        }

        // The other direction. Only files `emit` stamped: the hand-written
        // native pipelines share this directory and are none of its business.
        let mut orphaned = Vec::new();
        for name in listing(ctx, &committed)? {
            if fresh.contains(&name) {
                continue;
            }
            if ctx.read_to_string(committed.join(&name))?.contains(HEADER) {
                orphaned.push(name);
            }
        }

        if drifted.is_empty() && missing.is_empty() && orphaned.is_empty() {
            ctx.info(format!("{} generated workflow(s) match a fresh emit", fresh.len()));
            return Ok(());
        }

        let mut report = String::from("`.woodpecker/` disagrees with `.kiln/src`.\n");
        for (label, files) in
            [("changed", &drifted), ("never committed", &missing), ("generated but unregistered", &orphaned)]
        {
            if !files.is_empty() {
                report.push_str(&format!("  {label}: {}\n", files.join(" ")));
            }
        }
        if !orphaned.is_empty() {
            report.push_str("  An orphan still runs — `emit` overwrites but never deletes, so delete it by hand.\n");
        }
        report.push_str(&format!("Fix:\n{FIX}"));
        Err(ctx.err(report))
    })
}

/// The committed lockfile is what `describe` prints.
fn lockfile(ctx: &Ctx) -> Result<()> {
    ctx.step("lockfile drift", |ctx| {
        let fresh = ctx.run(me(ctx)?, ["describe"]).in_dir(ctx.workspace()).capture()?;
        let committed = ctx.read_to_string(ctx.workspace().join(LOCK))?;
        if fresh.trim() == committed.trim() {
            return Ok(());
        }
        Err(ctx.err(format!("{LOCK} is not what `describe` prints.\nFix:\n{FIX}")))
    })
}

/// The `.yml` files in `dir`, by name, sorted.
fn listing(ctx: &Ctx, dir: &Path) -> Result<Vec<String>> {
    let out = ctx.run("ls", ["-1"]).arg(dir).capture()?;
    let mut names: Vec<String> =
        out.lines().map(str::trim).filter(|n| n.ends_with(".yml")).map(str::to_owned).collect();
    names.sort();
    Ok(names)
}
