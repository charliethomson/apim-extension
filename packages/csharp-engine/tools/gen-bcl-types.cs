#!/usr/bin/env dotnet
// Generates assets/bcl-types.json: every public type name in the .NET reference assemblies and
// Newtonsoft.Json, by simple name, plus the public member names of the allowlist's restricted
// types. The allowed-types lint uses it to tell a forbidden BCL type from a local variable.
//
// Run from packages/csharp-engine: dotnet run tools/gen-bcl-types.cs
#:package System.Reflection.MetadataLoadContext@10.0.0
#:package Newtonsoft.Json@13.0.3
#:property PublishAot=false

using System.Reflection;
using System.Runtime.InteropServices;
using System.Text.Json;

var refDir = FindRefPack();
var newtonsoft = typeof(Newtonsoft.Json.JsonConvert).Assembly.Location;
var paths = Directory.GetFiles(refDir, "*.dll").Append(newtonsoft).ToList();
using var mlc = new MetadataLoadContext(new PathAssemblyResolver(paths));

var allowlist = JsonDocument.Parse(File.ReadAllText("assets/allowed-types.json")).RootElement.GetProperty("types");
var restricted = allowlist.EnumerateObject().Where(p => p.Value.ValueKind != JsonValueKind.String).Select(p => p.Name).ToHashSet();

var types = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
var members = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
foreach (var path in paths)
{
    Assembly asm;
    try { asm = mlc.LoadFromAssemblyPath(path); } catch { continue; }
    Type[] exported;
    try { exported = asm.GetExportedTypes(); } catch { continue; }
    foreach (var t in exported)
    {
        if (t.Namespace is null || t.IsNested) continue;
        if (!(t.Namespace == "System" || t.Namespace.StartsWith("System.") || t.Namespace.StartsWith("Newtonsoft.Json"))) continue;
        var simple = t.Name.Split('`')[0];
        if (!types.TryGetValue(simple, out var ns)) types[simple] = ns = new SortedSet<string>(StringComparer.Ordinal);
        ns.Add(t.Namespace);

        var full = t.FullName!;
        if (restricted.Contains(full))
        {
            var set = members.TryGetValue(full, out var s) ? s : members[full] = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var m in t.GetMembers(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static))
            {
                if (m is MethodInfo mi && mi.IsSpecialName) continue; // property accessors, operators
                set.Add(m is ConstructorInfo ? "(Constructor)" : m.Name);
            }
        }
    }
}

var output = new
{
    comment = $"Generated by tools/gen-bcl-types.cs from {Path.GetFileName(Path.GetDirectoryName(refDir))} reference assemblies and Newtonsoft.Json. Do not edit.",
    types = types.ToDictionary(kv => kv.Key, kv => kv.Value.ToArray()),
    members = members.ToDictionary(kv => kv.Key, kv => kv.Value.ToArray()),
};
File.WriteAllText("assets/bcl-types.json", JsonSerializer.Serialize(output, new JsonSerializerOptions { WriteIndented = false }) + "\n");
Console.WriteLine($"{types.Count} type names, {members.Count} restricted types");

static string FindRefPack()
{
    var dotnetRoot = Path.GetDirectoryName(Path.GetDirectoryName(RuntimeEnvironment.GetRuntimeDirectory().TrimEnd('/', '\\')))!;
    dotnetRoot = Path.GetDirectoryName(dotnetRoot)!; // .../shared/Microsoft.NETCore.App/x -> root
    var packs = Path.Combine(dotnetRoot, "packs", "Microsoft.NETCore.App.Ref");
    var version = Directory.GetDirectories(packs).OrderByDescending(d => Version.TryParse(Path.GetFileName(d).Split('-')[0], out var v) ? v : new Version()).First();
    return Directory.GetDirectories(Path.Combine(version, "ref")).OrderByDescending(d => d).First();
}
