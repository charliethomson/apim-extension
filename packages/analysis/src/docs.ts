/**
 * Markdown documentation for a fragment or a policy, from what the extension already knows: the
 * fragment header, the policy's structure, and the workspace around it. Pure: the caller supplies
 * the links (who includes it, where included fragments' docs are) and the inferred JSON shapes.
 */

import type { Document, Element, Node } from '@apim-policy/document';
import { matchesPattern, type FragmentVariable } from './fragmentDoc';
import { summarize } from './variables';

/** Marks a file this wrote, so writing again may replace it and never a hand-written one. */
export const GENERATED_MARKER = '<!-- Generated by the APIM Policy extension from the policy and its header; generating again rewrites it. -->';

export interface DocContext {
  /** Files that include the fragment, with a link to each when there is one. */
  callers?: readonly { label: string; href?: string }[];
  /** Where an included fragment's doc (or file) is, for links. */
  fragmentHref?: (id: string) => string | undefined;
  /** A variable's JSON shape as type text (`{ count: int }`), when the code shows one. */
  shapeText?: (name: string) => string | undefined;
  /** The policy's scope, for a policy (`API echo`). */
  scope?: string;
}

export function fragmentMarkdown(id: string, doc: Document, ctx: DocContext = {}): string {
  const summary = summarize(doc);
  const header = summary.header;
  const out: string[] = [GENERATED_MARKER, '', `# ${id}`, ''];
  if (header?.summary) out.push(inline(header.summary), '');
  if (!header) out.push('_This fragment has no header, so its inputs and outputs are inferred from what it reads and sets._', '');

  const typeOf = (v: { name: string; type?: string }) => v.type ?? ctx.shapeText?.(v.name);
  const inputs: FragmentVariable[] = header?.inputs ?? inferred(summary.reads.map((r) => r.name).filter((n) => !summary.variables.some((v) => v.name === n)));
  const outputs: FragmentVariable[] = header?.outputs ?? inferred(summary.variables.map((v) => v.name));

  out.push('## Inputs', '');
  if (inputs.length) {
    out.push('| Variable | Type | Required | Description |', '|---|---|---|---|');
    for (const v of inputs) out.push(`| ${code(v.name)} | ${typeCell(typeOf(v))} | ${v.optional ? (v.default !== undefined ? `no, default ${code(v.default)}` : 'no') : '**yes**'} | ${cell(v.description)} |`);
  } else out.push('None.');
  out.push('', '## Outputs', '');
  if (outputs.length) {
    out.push('| Variable | Type | Description |', '|---|---|---|');
    for (const v of outputs) out.push(`| ${code(v.name)} | ${typeCell(typeOf(v))} | ${cell(v.description)} |`);
  } else out.push('None.');

  out.push('', '## Usage', '', '```xml');
  for (const v of inputs.filter((x) => !x.optional)) out.push(`<set-variable name="${v.name}" value="" />`);
  out.push(`<include-fragment fragment-id="${id}" />`);
  if (outputs.length) out.push(`<!-- then read ${outputs.slice(0, 3).map((v) => v.name).join(', ')}${outputs.length > 3 ? ', …' : ''} -->`);
  out.push('```', '');

  if (header?.typedefDocs.size) {
    out.push('## Types', '');
    for (const t of header.typedefDocs.values()) {
      out.push(`### ${t.name}`, '');
      if (t.description) out.push(inline(t.description), '');
      if (t.legacy) {
        out.push(code(header.typedefs.get(t.name) ?? ''), '');
        continue;
      }
      out.push('| Key | Type | Required | Description |', '|---|---|---|---|');
      for (const p of t.properties) out.push(`| ${code(p.name)} | ${typeCell(p.type)} | ${p.optional ? 'no' : '**yes**'} | ${cell(p.description)} |`);
      out.push('');
    }
  }
  if (header?.internals.length) {
    out.push('## Internal variables', '', 'Set by the fragment for its own use. Callers should not read them; they may change.', '');
    for (const v of header.internals) {
      // A pattern lists what it covers, apart from variables with their own line.
      const named = new Set(header.internals.filter((x) => !x.name.includes('*')).map((x) => x.name));
      const sets = v.name.includes('*') ? summary.variables.map((s) => s.name).filter((n, i, all) => all.indexOf(n) === i && matchesPattern(v.name, n) && !named.has(n)) : [];
      out.push(`- ${code(v.name)}${typeOf(v) ? ` ${code(typeOf(v)!)}` : ''}${v.description ? `: ${inline(v.description)}` : ''}${sets.length ? ` (${sets.map(code).join(', ')})` : ''}`);
    }
    out.push('');
  }
  out.push(...dependencies(doc, ctx));
  if (ctx.callers) {
    out.push('## Used by', '');
    if (ctx.callers.length) for (const c of ctx.callers) out.push(`- ${c.href ? `[${inline(c.label)}](${c.href})` : inline(c.label)}`);
    else out.push('No policy in this workspace includes it.');
    out.push('');
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

export function policyMarkdown(title: string, doc: Document, ctx: DocContext = {}): string {
  const summary = summarize(doc);
  const out: string[] = [GENERATED_MARKER, '', `# ${title}`, ''];
  if (ctx.scope) out.push(`Scope: ${ctx.scope}.`, '');
  const sections = doc.root?.name === 'policies' ? doc.root.children.filter((n): n is Element => n.type === 'element') : [];
  if (sections.length) {
    out.push('## Steps', '');
    for (const s of sections) {
      const steps = s.children.filter((n): n is Element => n.type === 'element');
      out.push(`- **${s.name}**: ${steps.length ? steps.map((e) => step(e, ctx)).join(', ') : 'nothing'}`);
    }
    out.push('');
  }
  const set = [...new Set(summary.variables.map((v) => v.name))];
  const read = [...new Set(summary.reads.map((r) => r.name))].filter((n) => !set.includes(n));
  if (set.length || read.length) {
    out.push('## Variables', '');
    if (set.length) out.push(`- Sets: ${set.map((n) => `${code(n)}${ctx.shapeText?.(n) ? ` ${code(ctx.shapeText(n)!)}` : ''}`).join(', ')}`);
    if (read.length) out.push(`- Reads without setting: ${read.map(code).join(', ')}`);
    out.push('');
  }
  out.push(...dependencies(doc, ctx));
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

/** What a policy relies on outside itself: fragments, named values, backends, URLs it calls. */
function dependencies(doc: Document, ctx: DocContext): string[] {
  const summary = summarize(doc);
  const backends = new Set<string>();
  const urls = new Set<string>();
  const visit = (nodes: readonly Node[]) => {
    for (const n of nodes) {
      if (n.type !== 'element') continue;
      const literal = (name: string) => n.attributes.find((a) => a.name === name && !a.expression)?.value?.trim();
      if (n.name === 'set-backend-service') {
        const id = literal('backend-id');
        const base = literal('base-url');
        if (id) backends.add(id);
        if (base) urls.add(base);
      }
      if (n.name === 'set-url') {
        const text = n.children.find((c) => c.type === 'text' && !c.expression && c.value.trim());
        if (text?.type === 'text') urls.add(text.value.trim());
      }
      visit(n.children);
    }
  };
  visit(doc.children);
  const fragments = [...new Set(summary.includes)];
  const out: string[] = [];
  if (!fragments.length && !summary.namedValues.length && !backends.size && !urls.size) return out;
  out.push('## Depends on', '');
  if (fragments.length) out.push(`- Fragments: ${fragments.map((id) => (ctx.fragmentHref?.(id) ? `[${code(id)}](${ctx.fragmentHref(id)})` : code(id))).join(', ')}`);
  if (summary.namedValues.length) out.push(`- Named values: ${summary.namedValues.map((n) => code(`{{${n}}}`)).join(', ')}`);
  if (backends.size) out.push(`- Backends: ${[...backends].map(code).join(', ')}`);
  if (urls.size) out.push(`- Calls: ${[...urls].map(code).join(', ')}`);
  out.push('');
  return out;
}

function step(e: Element, ctx: DocContext): string {
  if (e.name === 'include-fragment') {
    const id = e.attributes.find((a) => a.name === 'fragment-id' && !a.expression)?.value?.trim();
    if (id) return ctx.fragmentHref?.(id) ? `[${code(`include ${id}`)}](${ctx.fragmentHref(id)})` : code(`include ${id}`);
  }
  if (e.name === 'set-variable') {
    const name = e.attributes.find((a) => a.name === 'name' && !a.expression)?.value?.trim();
    if (name) return code(`set ${name}`);
  }
  return code(e.name);
}

function inferred(names: string[]): FragmentVariable[] {
  return [...new Set(names)].map((name) => ({ name, range: { start: 0, end: 0 }, optional: false, description: '' }));
}

/** Inline code that holds any text: a longer fence when the text has backticks. */
function code(text: string): string {
  const ticks = '`'.repeat(Math.max(1, ...[...text.matchAll(/`+/g)].map((m) => m[0].length + 1)));
  const pad = text.startsWith('`') || text.endsWith('`') ? ' ' : '';
  return `${ticks}${pad}${text}${pad}${ticks}`;
}

function typeCell(type: string | undefined): string {
  return type ? code(type).replace(/\|/g, '\\|') : '';
}

/** Header text inside a table cell: no pipes, no line breaks. */
function cell(text: string): string {
  return inline(text).replace(/\|/g, '\\|');
}

/** Header text as Markdown text: what would format it (`*`, `_`, `<`) is escaped. */
function inline(text: string): string {
  return text.replace(/\s+/g, ' ').replace(/([\\*_[\]<>#])/g, '\\$1');
}

